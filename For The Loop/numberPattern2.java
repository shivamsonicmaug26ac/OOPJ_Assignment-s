
public class numberPattern2 {

	public static void main(String[] args) {
		
		int numb = 6;
		
		for(int Tempi = 1; Tempi <= numb; Tempi++) // 1
		{
			for(int Tempj = 1; Tempj<=Tempi; Tempj++) 
			{
				
				System.out.print(Tempj + " ");
				
			}
			System.out.println();
		}

	}

}
