
public class numberPattern3 {

	public static void main(String[] args) {
		
		int num = 6;
		
		for(int Tempi = num; Tempi>=1; Tempi--) {
			
			for(int Tempj = 1; Tempj<=Tempi; Tempj++) {
				
				System.out.print(Tempj +" ");
				
			}
			
			System.out.println();
			
		}

	}

}
